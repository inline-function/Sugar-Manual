            compareByDescending<EffectTag> { it.level }
                .thenByDescending { it.acute }
                .thenByDescending { if (it.pos || it.neuro > 0) 2 else if (it.neuro < 0) 1 else 0 }
                .thenByDescending { it.pack }
        )
