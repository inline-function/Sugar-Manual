    private fun acBoost(): Pair<Int, String>? {
        var w = 0; val sb = StringBuilder()
        profCondsState.value.sorted().forEach { c -> if (c.contains("痴呆") || c.contains("认知障碍")) { w += 2; if (sb.isNotEmpty()) sb.append("，"); sb.append("$c +2") } }
